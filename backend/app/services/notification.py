"""Multi-channel notification service supporting FCM, Telegram, and LINE."""

import asyncio
from typing import Optional
import httpx
from loguru import logger
from app.core.config import get_settings


class NotificationService:
    def __init__(self):
        self.cfg = get_settings()

    async def send_signal_alert(
        self,
        symbol: str,
        timeframe: str,
        direction: str,
        message: str,
        confluence_score: int,
        entry: Optional[float] = None,
        sl: Optional[float] = None,
        tp: Optional[float] = None,
        rr: Optional[float] = None,
        contract_mode: Optional[str] = None,
        action_label: Optional[str] = None,
    ) -> dict[str, bool]:
        """Broadcast signal alert to all configured channels (FCM, Telegram, LINE)."""
        results = {}

        if not action_label:
            mode = contract_mode or (
                "spot"
                if (
                    symbol.upper().endswith("/THB")
                    or (get_settings().binance_trading_mode == "spot" and symbol.upper().endswith("/USDT"))
                )
                else "futures"
            )
            if mode == "spot":
                action_label = "BUY (SPOT)" if direction.upper() in ("LONG", "BUY") else "SELL (SPOT)"
            else:
                action_label = direction.upper()

        tg_success, line_success, fcm_success = await asyncio.gather(
            self._send_telegram(
                symbol=symbol,
                timeframe=timeframe,
                direction=action_label,
                message=message,
                confluence=confluence_score,
                entry=entry,
                sl=sl,
                tp=tp,
                rr=rr,
            ),
            self._send_line(
                symbol=symbol,
                timeframe=timeframe,
                direction=action_label,
                message=message,
                confluence=confluence_score,
            ),
            self._send_fcm(
                title=f"🚨 Apex Signal: {action_label} {symbol} ({timeframe})",
                body=message,
                data={
                    "symbol": symbol,
                    "timeframe": timeframe,
                    "direction": direction,
                    "contract_mode": contract_mode or ("spot" if "SPOT" in action_label else "futures"),
                    "action_label": action_label,
                },
            ),
        )
        results["telegram"] = tg_success
        results["line"] = line_success
        results["fcm"] = fcm_success

        try:
            from app.api.ws import broadcast

            await broadcast({
                "type": "app_notification",
                "data": {
                    "title": f"🚨 Apex Signal: {action_label} {symbol} ({timeframe})",
                    "body": message,
                    "symbol": symbol,
                    "timeframe": timeframe,
                    "direction": direction,
                    "contract_mode": contract_mode or ("spot" if "SPOT" in action_label else "futures"),
                    "action_label": action_label,
                    "confluence": confluence_score,
                    "entry": entry,
                    "sl": sl,
                    "tp": tp,
                    "rr": rr,
                },
            })
            results["ws"] = True
        except Exception as e:
            logger.debug(f"Failed to broadcast WS app_notification: {e}")
            results["ws"] = False

        return results

    async def _send_telegram(
        self,
        symbol: str,
        timeframe: str,
        direction: str,
        message: str,
        confluence: int,
        entry: Optional[float] = None,
        sl: Optional[float] = None,
        tp: Optional[float] = None,
        rr: Optional[float] = None,
    ) -> bool:
        from app.core.runtime_config import load_runtime_config
        rc = load_runtime_config()
        tg_token = (rc.get("telegram_token") or self.cfg.telegram_bot_token or "").strip()
        tg_chat = (rc.get("telegram_chat_id") or self.cfg.telegram_chat_id or "").strip()
        if not tg_token or not tg_chat:
            return False

        icon = "🟢" if direction.lower() == "long" else "🔴" if direction.lower() == "short" else "⚠️"
        text_lines = [
            f"{icon} APEX TRADING SIGNAL",
            "━━━━━━━━━━━━━━━━━━",
            f"Symbol: {symbol} | TF: {timeframe}",
            f"Direction: {direction.upper()}",
            f"Confluence: {confluence}/100",
            "",
        ]

        if entry and sl and tp:
            text_lines.extend([
                f"📍 Entry: {entry}",
                f"🛑 Stop Loss: {sl}",
                f"🎯 Take Profit: {tp}",
                f"⚖️ R:R Ratio: {rr or 'N/A'}",
                "",
            ])

        text_lines.extend([
            "Analysis:",
            f"{message}",
            "",
            "⏱ Generated by Apex AI Trade Advisor",
        ])

        payload = {
            "chat_id": tg_chat,
            "text": "\n".join(text_lines),
        }

        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                url = f"https://api.telegram.org/bot{tg_token}/sendMessage"
                resp = await client.post(url, json=payload)
                return resp.status_code == 200
        except Exception as e:
            logger.error(f"Failed to send Telegram alert: {e}")
            return False

    async def _send_line(
        self,
        symbol: str,
        timeframe: str,
        direction: str,
        message: str,
        confluence: int,
    ) -> bool:
        from app.core.runtime_config import load_runtime_config
        rc = load_runtime_config()
        token = (rc.get("line_token") or self.cfg.line_notify_token or "").strip()
        if not token:
            return False

        line_msg = f"[Apex Signal] {direction.upper()} {symbol} ({timeframe})\nConfluence: {confluence}/100\n\n{message}"
        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                # 1. Try LINE Messaging API Broadcast first (Modern LINE Bot)
                headers = {
                    "Authorization": f"Bearer {token}",
                    "Content-Type": "application/json",
                }
                payload = {
                    "messages": [{"type": "text", "text": line_msg}]
                }
                resp = await client.post(
                    "https://api.line.me/v2/bot/message/broadcast",
                    headers=headers,
                    json=payload,
                )
                if resp.status_code == 200:
                    return True
                logger.warning(
                    f"[LINE] Messaging API broadcast failed with HTTP {resp.status_code}: {resp.text}"
                )
                return False
        except Exception as e:
            logger.error(f"Failed to send LINE alert: {e}")
            return False

    async def _send_fcm(self, title: str, body: str, data: dict) -> bool:
        server_key = (self.cfg.fcm_server_key or "").strip()
        if not server_key:
            return False

        # Google decommissioned the legacy FCM HTTP API (fcm.googleapis.com/fcm/send) in June 2024.
        # Mobile push delivery requires Firebase HTTP v1 API using OAuth2 service account tokens.
        logger.warning(
            "[FCM] Push skipped: Legacy FCM Server Key API was sunset by Google. "
            "Please migrate to Firebase HTTP v1 API with service account credentials."
        )
        return False
